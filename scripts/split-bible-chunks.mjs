import fs from 'node:fs';

const packed = JSON.parse(fs.readFileSync('assets/bible/amharic_bible.txt', 'utf8'));
const outDir = 'assets/bible/chunks';
fs.mkdirSync(outDir, { recursive: true });

const size = 9;
const files = [];
for (let i = 0; i < packed.books.length; i += size) {
  const slice = packed.books.slice(i, i + size).map((book) => ({
    ...book,
    chapters: book.chapters.map((chapter) => ({
      chapter: chapter.chapter,
      title: chapter.title,
      verses: chapter.verses,
    })),
  }));
  const name = String(files.length).padStart(2, '0') + '.txt';
  fs.writeFileSync(`${outDir}/${name}`, JSON.stringify(slice));
  files.push(name);
}

fs.writeFileSync(
  `${outDir}/manifest.json`,
  JSON.stringify({ title: packed.title, source: packed.source, files, bookCount: packed.books.length }),
);

const requires = files
  .map((file, index) => `  require('../../assets/bible/chunks/${file}'), // ${index}`)
  .join('\n');

fs.writeFileSync(
  'src/data/bibleChunks.ts',
  `// Auto-generated by scripts/split-bible-chunks.mjs — do not edit by hand.
export const packedBibleChunks: Array<number | { uri: string }> = [
${requires}
];
`,
);

console.log(
  JSON.stringify(
    {
      chunks: files.length,
      bytes: files.map((file) => fs.statSync(`${outDir}/${file}`).size),
    },
    null,
    2,
  ),
);
